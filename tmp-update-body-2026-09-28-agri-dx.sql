## 置き場所：紙1枚／チャット固定／スプレッドシート1行

道具は現場の習慣に合わせます。最初から専用システムは不要です。

### 1. 紙1枚（ハウス入り口や作業場）

- 朝書いた3行を貼る／マグネットで差し替える
- 完了は同じ紙にチェック、夜に日誌へ転記
- 電波や端末が弱い現場向き

### 2. 家族チャットの「今日の指示」スレ（固定メッセージ）

- 毎朝、同じ型で上書きまたは日付見出しで投稿
- 写真は任意（気になる株だけ）
- パートさんがチャットにいない場合は、紙と併用

### 3. スプレッドシート1行（日付・担当・3行・完了）

- 後から検索しやすい
- 列を増やしすぎない（日付／担当／指示本文／完了／メモ 程度）
- 日誌アプリがあるなら、指示欄を別シートにしてリンクだけでもよい

どれを選んでも、成功条件は同じです。

- **出勤前に、その日動く人が同じ3行を見られる**
- **夕方までに、完了メモが日誌側へ戻っている**

農業DX構想2.0でも、生産現場から流通・消費までのデジタル化の道筋が示されています。中小の施設栽培では、構想の全体像を一度に実装するより、**日次の共有が続く型**から入る方が、あとでセンサーや出荷記録とつなぎやすい、というのが実務上の順序です。

