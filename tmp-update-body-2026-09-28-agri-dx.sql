## 倉吉の1農家で現実的だった育て方（目安）

前回の日誌→センサーの順番に、指示の層を足すと次のようになります。期間は目安です。

### 週0〜1：口頭の内容を書き出す

出がけに言っていることを、3行テンプレに当てはめてみるだけです。まだ共有しなくて構いません。書けない朝は、指示がそもそも曖昧なサインです。

### 週1〜2：家族だけで毎朝3行を共有

チャットまたは紙で、家族だけで回します。パートさんへの展開はまだしません。直すのは文面の曖昧さだけです。

### 週2〜4：パート出勤日に同じ型で渡す

本線が安定したら、パートさん向けにも同じ3行を渡します。口頭補足は「地図と安全」に限り、作業内容の本体は文書側に残します。

### その後：センサー異常や出荷都合を「注意」行へ接続

温度通知や出荷変更は、2行目の注意に1つだけ載せます。ダッシュボードを朝の必須読ませにはしません。

この順番は、前回の「日誌が先、センサーは後」と同じ型です。指示の型がないまま通知を増やすと、朝の情報がまた散らばります。

## よくあるつまずきと対処

### 「3行に収まらず、毎朝長文になる」

本線が複数あるか、担当が決まっていないことが多いです。作業を削るのではなく、**担当ごとに3行を分ける**か、**本線を1本に戻す**かを選びます。全員向けの長文は続きません。

### 「書いたのに読まれない」

置き場所が分散しているか、書く時刻が遅すぎます。出勤前に固定場所へ出す、を先に守ります。文面の洗練より、**同じ場所・同じ時刻**が効きます。

### 「完了メモが戻らず、日誌と指示が分断する」

3行目に完了の書き方を固定し、夕方の1分をルーチンにします。完璧な実績入力より、「完了時刻＋残し」の1行で十分です。戻らない日が続くなら、入力項目が多すぎないか見直します。

### 「週次ボードを先に作りたくなる」

週次は有益ですが、日次が口頭のままなら効き目は薄いです。週次を作りたくなったら、日次が2週間続いているかを先に確認します。続いていれば、週次は薄く足せます。

### 「アプリを入れれば指示も自動で出るはず、と思う」

ツールは補助です。誰が今日の本線を決めるか、という役割が先です。代表不在日の最終決定者を名前で書くだけでも、現場の迷いは減ることがあります。自動生成の指示文は、型が固まってからの検討で十分です。

## 向く条件・向かない条件

### 向くことが多い

- 家族＋パートなど、**毎日同じ顔ぶれで短い指示が必要**
- 日誌（または同等の作業記録）が、ほぼ毎日残っている
- 代表の外出・打ち合わせがあり、口頭だけでは当日がぶれる
- 「立派な計画」より、朝のすれ違いを減らしたい

### 向かない／先に別の整理がよい

- 日誌自体が週に数回しか残っていない（先に [日誌の毎日1本](https://www.studiofoods.net/blog/kurayoshi-one-farm-diary-sensor) 側）
- 従業員が多く、シフト・資格・安全手順が帳票レベルで必須（労務・安全の専門家と設計）
- 取引先ごとに複雑な出荷指示が毎朝必要で、3行に圧縮できない（出荷チェック表を別型で切る）
- 週次の経営判断（作付・投資）が本題（本稿の範囲外）

## 朝10分でできるチェックリスト

- 昨日の日誌に、未完了と気づきが残っているか
- 今日の本線は1本か（担当名と場所があるか）
- 注意は1つに絞れているか
- 完了メモの書き方が3行目にあるか
- 出勤前に、動く人が同じ場所で読めるか
- 代表不在なら、最終決定者の名前があるか
- 週次の話を日次の3行に混ぜていないか

## まとめ

- 日誌が回り始めたあとの次の詰まりは、**今日の作業指示が口頭のまま**であること多い
- 週次の判断ボードと、日次の引き継ぎはレイヤーが違う。先に日次の型を薄く定着させる
- **朝の3行**（誰が・どこで・何を／注意1つ／完了メモ）が、家族・パートへの最小の渡し方になる
- 材料は昨日の日誌。全部は写さず、本線1本に圧縮する
- 道具は紙・チャット・1行シートのどれでもよい。成功条件は「出勤前に同じ3行」「完了が日誌へ戻る」
- センサー通知や出荷都合は、注意行に1つだけ載せる。朝の必須画面を増やさない

