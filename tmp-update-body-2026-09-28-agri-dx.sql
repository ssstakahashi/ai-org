## 日誌が残っても、朝の引き継ぎが口頭のままになる理由

施設栽培の家族経営では、次のズレが同時に起きやすいです。

### 1. 日誌は「過去」、指示は「今日」

日誌の成功条件は、「その日のうちに、その日の作業が未入力のまま残らない」でした。一方、朝の成功条件は別物です。

- **誰が**（本人／家族／パート）
- **どこで**（ハウス番号・区画）
- **何を・どこまで**（摘葉、灌水確認、出荷箱詰め、など）
- **やらないこと**（今日はやらない作業）

過去の記録が充実しても、今日の割り当てが書かれていなければ、現場はまた口頭に戻ります。

### 2. 「全部見える画面」が、逆に探しにくくする

営農アプリやスプレッドシートに項目を増やしすぎると、朝の5分で読むべき行が埋もれます。センサーのグラフ、過去の防除履歴、在庫表——どれも価値はありますが、**朝一番に必要なのは短い指示**です。[SODATEで最初の要件を小さく切る](https://www.studiofoods.net/blog/sodate-carve-first-requirement) と同じく、先に切るのは機能一覧ではなく、現場が毎日回している1本の流れです。

### 3. 週次の判断と、日次の渡し方が混ざる

「今週の優先」を週1回決める話と、「今朝パートさんに渡す3行」はレイヤーが違います。週次は振り返りと判断、日次は実行の共有です。混ざると、週次ボードが厚くなり、朝はまた口頭に戻る、というパターンが起きやすいです。本稿は後者だけを扱います。

### 4. 人が減る前提では、「頭の中」がボトルネックになる

スマート農業技術活用促進法は、農業者の減少等の環境変化に対応し、生産性向上のためスマート農業技術の活用を促す枠組みとして、令和6年10月に施行されています。機械導入の話と同時に、現場では**代表の頭の中に閉じた当日指示を外に出す**ことが、小さな家族経営でも効きやすい一手になります。制度の認定や支援措置の詳細は、個別に公式情報と専門家の確認が前提です。

出典: [スマート農業技術活用促進法について（農林水産省）](https://www.maff.go.jp/j/kanbo/smart/houritsu.html)

## 週次判断と日次指示：役割を分ける

用語は厳密なプロジェクト管理を強制するものではありません。倉吉規模の現場では、次の二層で足りることが多いです。

| 層 | 目的 | 頻度 | 読む人 | 例 |
| --- | --- | --- | --- | --- |
| **週次の判断** | 優先と振り返り | 週1回程度 | 代表＋家族 | 今週はハウスAの摘葉を厚め／出荷ピークの人員 |
| **日次の指示** | 今日の実行共有 | **毎朝** | その日動く全員 | Aさん：ハウス2摘葉〜10時／注意：薬散布後の入室 |

週次を先に立派にすると、日次が後回しになりがちです。日誌が回り始めた直後は、**日次の3行を先に定着させた方が効く**現場が多い、というのが本稿の立場です。週次ボードは、日次が1〜2週間続いたあとに薄く足せば十分です。

## 「朝の3行指示」テンプレ

紙でもチャットでもスプレッドシートでも構いません。重要なのは、毎朝同じ型で書くことです。

### A. 3行の中身（これ以上増やさない）

1. **誰が・どこで・何を（どこまで）**  
   例：`Aさん／ハウス2／摘葉。通路側から中央まで。10時目安`
2. **今日の注意（1つだけ強く）**  
   例：`昨日の薬散布あり。入室前に表示を確認。温度は朝の見回りメモ参照`
3. **終わったら書く一言（完了メモ）**  
   例：`完了時刻と「残し／気になる株」を日誌に1行`

3行を超えると、朝の読む時間が伸び、口頭に戻ります。追加作業がある日は、「今日の本線はこれ／余力があればこれ」の2段までにします。

### B. 弱い文／使える文

| 弱い文（避ける） | 使える文（例） |
| --- | --- |
| ハウスの手入れをお願い | Aさん：ハウス2の摘葉。通路側から中央まで。10時まで |
| いつもどおりで | 昨日の続き。未完了の株札がある列から |
| 気をつけて | 薬散布翌日。入室前に表示確認。手袋替え |
| 終わったら連絡 | 日誌に完了時刻＋残し列を1行。写真任意 |
| 全体を見ておいて | 本線は摘葉。余力があれば灌水チューブの確認のみ |

判定は夕方（または翌日の朝）に **渡した／実行できた／指示が曖昧だった** の三択で十分です。「だいたい伝わった」は曖昧だった側へ寄せます。

### C. 日誌から指示を書くときの材料（前夜 or 早朝5分）

日誌の昨日分を開き、次だけ拾います。

- 未完了・持ち越し（昨日やりきれなかったこと）
- センサー／見回りで気になった点（温度異常のあとなど）
- 出荷・取引先の都合（箱数、規格、引き取り時間）
- 人が変わる日（パート出勤、代表外出）

全部を指示に書き写しません。**今日の本線1本＋注意1つ**に圧縮します。圧縮できない日は、作業が多すぎるか、誰がやるかが決まっていないサインです。

