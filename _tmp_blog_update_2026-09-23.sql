- **給与反映**: 決定通知後のソフト更新、当月／翌月徴収の説明、協会けんぽ料額表との突合

## 賞与（標準賞与額）への短い触れ方

定時決定・随時改定の主役は月額の標準報酬ですが、賞与は**標準賞与額**という別レーンです。日本年金機構の案内では、賞与を支給したときは「被保険者賞与支払届」により支給額等を届け出ます。税引前の総支給額から1,000円未満を切り捨てた額が標準賞与額となり、これに健康保険料率・厚生年金保険料率をかけて保険料を計算します（折半が原則）。

上限の目安（機構FAQ等の一般的な整理）:

- **健康保険**: 年度（4/1〜翌3/31）の累計で573万円  
- **厚生年金**: 1カ月あたり150万円（同月に複数回なら合算）

年4回以上支給されるものは、標準賞与ではなく標準報酬月額側の報酬として扱う、という整理もあります。賞与支払届の期限は支給日から5日以内、といった案内があるため、給与ソフトの賞与レースと届出カレンダーを分けて管理すると漏れが減ります。

公式（賞与を支給したとき）: https://www.nenkin.go.jp/service/kounen/hokenryo/hoshu/20141203.html  
公式（賞与の保険料計算FAQ）: https://www.nenkin.go.jp/section/faq/kounen/hokenryo/shoyokeisan.html

本稿では賞与の深掘りはここまでとし、月額の定時決定／随時改定に戻ります。

## 9月分保険料と「給与からいつ引かれるか」

定時決定で決まった新標準報酬は、原則**9月分の保険料から**適用されます。一方、事業主が被保険者負担分を給与から差し引くタイミングは、労働基準法上の制限の範囲で、多くの事業所が**翌月徴収**（当月支給給与から前月分を控除）を採用しています。

日本年金機構の納付案内では、例えば5月の給料支払日には4月分の保険料を差し引くことができる、と説明されています。納付期限は対象月の翌月末、という整理です。

したがって、「9月分から等級が上がった」＝「9月支給の給与明細ですぐ控除額が増える」とは限りません。翌月徴収なら、**10月支給の給与**で9月分が控除されるイメージになります。就業規則・賃金規程・給与ソフトの設定を必ず突合してください。

公式（保険料の納付）: https://www.nenkin.go.jp/service/kounen/hokenryo/nofu/nofu.html

