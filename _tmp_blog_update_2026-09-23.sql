## よくある質問（現場向け）

**Q. 基本給は据え置き、残業だけ急増しました。月額変更届は必要ですか。**  
A. 残業手当など非固定的賃金だけの変動では、随時改定の要件（固定的賃金の変動）を満たさない、というのが一般的な整理です。一方、その残業が4〜6月に載れば定時決定側には効きます。

**Q. 7月に昇給しました。算定基礎届と月額変更、どちらですか。**  
A. 7月改定の随時改定に該当する場合は月額変更届側になり、算定基礎届の提出対象から外れる案内があります。要件（固定変動・2等級・日数）を先に判定してください。

**Q. パートの支払基礎日数は17日ですか、11日ですか。**  
A. 「短時間就労者」と「特定適用事業所等の短時間労働者」で基準が異なります。被保険者区分を取り違えると算定月が変わるため、資格取得時の区分と機構の該当節を突合してください。

## 中小が今シーズンやっておくとよいこと

1. **4〜6月の支給台帳を、算定用に別ブックへ固定する**（後から明細を探し回らない）  
2. **固定的賃金の改定カレンダー**（最低賃金・手当改定・昇格）を月変シミュレーションと結びつける  
3. **決定通知の到着〜給与反映**の担当と期限を決める（通知遅れも機構側で言及あり）  
4. **本人説明の一文**を用意する（「9月分から等級が変わる／控除は翌月支給」など事業所ルールに合わせて）  
5. 迷ったら、電子申請サポートや年金事務所・社労士に**早期に**聞く（7月10日直前は混みやすい）

