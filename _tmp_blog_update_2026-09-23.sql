## 標準報酬月額とは何か（現場の言葉で）

給与明細に載る「社会保険料」は、その月の残業込みの総支給額にそのまま料率をかけたものではありません。日本年金機構の整理では、被保険者の報酬を一定の幅（等級）に当てはめた**標準報酬月額**を基礎に、健康保険料・厚生年金保険料を計算します。

- **毎月の保険料**: 標準報酬月額 × 保険料率（事業主と被保険者で折半が原則）
- **賞与の保険料**: 標準賞与額 × 保険料率（別途。後述）

標準報酬月額が上がれば、毎月の保険料負担（会社・本人とも）が増えます。将来の年金額の計算基礎にもつながるため、「高くすると損」と単純化せず、**実際の報酬に近い等級になっているか**を年次で確認する、という視点が実務では使いやすいです。

協会けんぽ加入の場合、都道府県ごとの健康保険料率は協会けんぽの公表を、厚生年金の料率は日本年金機構の案内を入口にしてください。料率そのものの一覧は本稿では固定せず、**等級の決まり方**に焦点を当てます。

## 定時決定（算定基礎届）— 4〜6月が効く理由

### 何をする手続きか

日本年金機構の案内（定時決定・算定基礎届）によれば、事業主は**7月1日現在**で使用している被保険者（および70歳以上被用者）について、その年の**4月・5月・6月**に受けた報酬月額を算定基礎届で届け出ます。厚生労働大臣はこれに基づき、毎年1回、標準報酬月額を決定し直します。これを**定時決定**といいます。

決定し直された標準報酬月額は、原則として**その年の9月から翌年8月まで**の各月に適用されます。

令和8年度（2026年度）については、日本年金機構が提出期限を**2026年7月10日（金）**と案内しています。様式は6月中旬以降に順次送付される想定です。電子申請の利用も推奨されています。最新の提出案内は必ず機構の特設・事務説明ページで確認してください。

公式（定時決定）: https://www.nenkin.go.jp/service/kounen/hokenryo/hoshu/20121017.html  
公式（令和8年度の提出案内）: https://www.nenkin.go.jp/tokusetsu/santei.html  
届書の入口: https://www.nenkin.go.jp/shinsei/kounen/tekiyo/hoshu/20141225.html

### 決定の考え方（一般被保険者）

一般的な整理では、4・5・6月のうち**支払基礎日数が17日以上**の月の報酬を平均し、その額を等級表に当てはめて標準報酬月額を決めます。支払基礎日数は、給与計算の対象となる日数です（月給・週給は暦日数、日給・時給は出勤日数、といった整理が機構の案内にあります）。

特定適用事業所等の短時間労働者については、支払基礎日数の基準が**11日以上**になるなど、一般の17日ルールとは扱いが異なります。パート・アルバイトの算定は、機構の「短時間就労者」「短時間労働者」の節を別途確認してください。

### 提出が不要・例外になりやすい人

機構の案内では、次のような方は算定基礎届の提出が不要とされています（一般的な整理）。

1. 6月1日以降に資格取得した方  
2. 6月30日以前に退職した方  
3. 7月改定の月額変更届を提出する方  
4. 8月または9月に随時改定が予定されている旨の申し出を行った方  

（3）（4）については、紙の算定基礎届では報酬欄を空欄にし備考の「月額変更予定」に〇を付ける、電子申請では対象外として作成する、といった案内があります。予定していた随時改定に該当しなかった場合は、速やかに算定基礎届を出す、というフォローも案内されています。現場では「算定を出したつもり／出さないつもり」のすれ違いが起きやすいので、月額変更との関係をチェックリストに入れておくと安心です。

### なぜ「残業が多い4〜6月」が痛く感じるか

定時決定の平均には、基本給だけでなく、その期間に実際に支払われた報酬（残業手当などの非固定的賃金を含む）が入ります。繁忙期が4〜6月に重なる業種では、一時的な残業増が年間の標準報酬月額を押し上げ、**9月以降もその等級が続く**、というのが現場でよく聞くパターンです。

一方で、後述の随時改定は「残業が増えただけ」では原則として対象になりません。つまり、

- **定時決定**: 4〜6月の実報酬（残業込み）が効く  
- **随時改定**: 固定的賃金の変動が起点  

という二段構えです。「残業を抑えて等級を下げる」ための回避術を勧める趣旨ではなく、**観測期間と届出の役割分担を先に理解する**ことが目的です。業務の平準化や手当設計は労務・経営の判断であり、個別の最適化は社労士等と相談してください。

### 年間平均による保険者算定

4〜6月の平均が例年の報酬と比べて著しく不当になる場合など、一定の条件のもとで**年間報酬の平均**による申立てができる取扱いがあります。申立書・同意書等の添付が必要で、機構の様式ページに案内があります。使うかどうかはケースバイケースです。安易に「得する方を選ぶ」話ではなく、実情に近い標準報酬にする手段の一つ、と捉えてください。

## 随時改定（月額変更届）— 残業だけでは動かない

### 何をする手続きか

被保険者の報酬が昇給・降給等で大幅に変わったとき、定時決定を待たずに標準報酬月額を見直すのが**随時改定**です。事業主は「被保険者報酬月額変更届」を速やかに提出します。

改定のタイミングは、変更後の報酬を**初めて受けた月（変動月）から起算して4カ月目**です。例: 4月支払の給与から固定的賃金が変わった場合、7月から新標準報酬、というイメージです。

- 6月までに随時改定された標準報酬は、再び随時改定がなければ**当年8月まで**適用  
- 7月以降に改定された場合は、原則**翌年8月まで**適用  

公式（随時改定）: https://www.nenkin.go.jp/service/kounen/hokenryo/hoshu/20150515-02.html  
届書の入口: https://www.nenkin.go.jp/shinsei/kounen/tekiyo/hoshu/20141224.html

### 3つの要件（すべて該当）

機構の案内では、次の（1）〜（3）に**すべて**該当した場合に随時改定を行います。

#### （1）固定的賃金の変動

固定的賃金とは、支給額や支給率が決まっているものをいいます。該当例として機構が挙げるものには次があります。

- 昇給（ベースアップ）、降給（ベースダウン）  
- 給与体系の変更（日給から月給など）  
- 日給・時間給の基礎単価の変更  
- 請負給・歩合給の単価・歩合率の変更  
- 住宅手当・役付手当など固定的手当の追加・額変更  
- 一時帰休に伴う休業手当の継続的な低額支給／解消、など  

一方、**残業手当などの非固定的賃金の増減だけ**では、固定的賃金の変動には当たりません。休職給を受けた場合も、固定的賃金の変動には該当しない、という整理が案内されています。

#### （2）2等級以上の差

変動月以後引き続く3カ月の報酬の平均から算出した標準報酬月額と、従前の標準報酬月額との間に**2等級以上**の差が生じること。さかのぼり昇給で差額が支払われた場合は、差額支給月を変動月とし、差額を差し引いた3カ月平均で比較する、といった取扱いも案内されています。

上限・下限の等級をまたぐ場合は、**1等級差でも随時改定の対象になる**ケースがあります（厚生年金・健康保険それぞれ機構の表を参照）。

#### （3）支払基礎日数

変動月以後の3カ月とも、支払基礎日数が**17日以上**（特定適用事業所の短時間労働者は**11日以上**）であること。

### 随時改定にならない典型例（機構の留意事項）

次の場合は、随時改定の対象とならない、と案内されています。

- 固定的賃金は上がったが、残業等が減って平均報酬が下がり、2等級以上下がった場合  
- 固定的賃金は下がったが、残業等が増えて平均報酬が上がり、2等級以上上がった場合  

「固定の動き」と「非固定の動き」の向きが一致しないと、等級差があっても随時改定に乗らない、という整理です。現場ではここを見落とすと、「昇給したのに月変が出ない／出すべきでないのに出した」の混乱につながります。

