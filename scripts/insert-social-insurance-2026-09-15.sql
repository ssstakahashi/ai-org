## 3. 同タイミングの支援策——保険料調整制度

加入拡大で新たに社会保険の対象になる短時間労働者の就業調整を減らすため、特例的・時限的に保険料負担を軽減する**保険料調整制度**が、日本年金機構の案内では**令和8年10月1日から**開始するとされています。

概要（公開案内の整理）は次のとおりです。

- 事業主が申出により、被保険者の保険料を一時的に一部負担し、対象者の健康保険・厚生年金保険の保険料負担を**通算3年間**軽減できる
- 対象となる被保険者の例：短時間労働者として加入する方のうち、**標準報酬月額が12.6万円以下**の方
- 事業主が追加負担した分は、一定期間後に調整され、最終的に事業主が納付する保険料は増えない、という説明がある（被保険者の将来の年金額にも影響しない旨）
- 対象事業所・申出期限は制度ページで区分されている（例：令和8年10月1日以降に任意特定適用事業所になる場合など）

出典：日本年金機構「保険料調整制度のご案内」 https://www.nenkin.go.jp/tokusetsu/hokenryochosei.html

厚生労働省の適用拡大ページでも、従業員数50人以下の企業などで新たに加入対象となる短時間労働者（標準報酬月額12.6万円以下）について、事業主が負担割合を増やし被保険者負担を軽減でき、追加負担分は制度全体で支援する、と整理されています。

出典：厚生労働省「社会保険の加入対象の拡大について」（就業調整を減らすための支援策） https://www.mhlw.go.jp/stf/seisakunitsuite/bunya/0000147284_00021.html

