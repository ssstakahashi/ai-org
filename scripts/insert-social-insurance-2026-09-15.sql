## 2. 令和8年10月予定——賃金要件（106万円の壁）の撤廃

厚生労働省の特設サイトでは、短時間労働者の社会保険加入について、いわゆる「年収106万円の壁」として意識されていた**月額8.8万円以上の賃金要件を撤廃する**方針が示されています。撤廃の時期は、全国の最低賃金が時給1,016円以上となることを見極めたうえで、**令和8年（2026年）10月に撤廃予定**と案内されています。

最低賃金が一定水準を超える地域では、週20時間以上働くと年額換算でおおよそ106万円前後になりやすい、というのが「壁」として意識されてきた背景です。要件が外れると、「収入を意識して時間を抑える」より、「週20時間以上かどうか」など、残る要件の確認が中心になります。

出典：厚生労働省「社会保険の加入対象の拡大について」 https://www.mhlw.go.jp/stf/seisakunitsuite/bunya/0000147284_00021.html

厚生労働省の加入要件ページでも、所定内賃金の月額8.8万円以上について「2026年10月に賃金要件を撤廃予定」と明記されています。

出典：厚生労働省 社会保険適用拡大特設サイト「社会保険加入の要件」 https://www.mhlw.go.jp/tekiyoukakudai/jugyouin/taisho/

