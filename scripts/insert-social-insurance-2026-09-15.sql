## 1. すでに動いている話——在職老齢年金の基準額（令和8年4月）

働きながら老齢厚生年金を受け取る場合、賃金（総報酬月額相当額）と老齢厚生年金（基本月額）の合計が基準額を超えると、超えた額の半分が支給停止されるのが在職老齢年金制度です。老齢基礎年金は調整対象になりません。

日本年金機構の案内では、令和7年年金制度改正法（令和7年法律第74号）に基づき、**令和8年4月から基準額が月51万円から65万円に引き上げられた**とされています。政府広報オンラインでも、賃金＋老齢厚生年金の合計が56万円の例では、改正前は一部支給停止だったものが、基準額65万円への引上げ後は全額支給となり、年間換算で約30万円の差になる、といった説明が示されています。

出典：
- 日本年金機構「在職老齢年金の計算方法」（令和8年4月更新） https://www.nenkin.go.jp/service/jukyu/seido/roureinenkin/zaishoku/20150401-01.html
- 政府広報オンライン「もっと働きたい！に応えて、在職老齢年金制度の基準額が2026年4月から引上げに」 https://www.gov-online.go.jp/tokusyu/roureinenkin/

