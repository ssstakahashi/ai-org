## 4. その先——企業規模要件の段階的な拡大

賃金要件の話と並行して、企業規模要件も段階的に動きます。厚生労働省・日本年金機構の案内では、短時間労働者の適用対象となる企業の範囲が、おおむね次のように拡大するとされています。

- 現時点の中心：厚生年金被保険者数**51人以上**
- **令和9年（2027年）10月〜**：36人以上
- **令和11年（2029年）10月〜**：21人以上
- **令和14年（2032年）10月〜**：11人以上
- **令和17年（2035年）10月〜**：10人以下

出典：
- 厚生労働省 社会保険適用拡大特設サイト「社会保険加入の要件」 https://www.mhlw.go.jp/tekiyoukakudai/jugyouin/taisho/
- 日本年金機構「短時間労働者に対する健康保険・厚生年金保険の適用の拡大」 https://www.nenkin.go.jp/service/kounen/tekiyo/jigyosho/tanjikan.html

人数の数え方（法人番号が同一の全事業所合算、短時間労働者を含めない、など）は案内の定義に従います。36〜50人規模の事業所は、2027年10月に向けた準備期間が実質的に始まっている、と捉えると動きやすいです。

