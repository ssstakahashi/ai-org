## なぜ「短い」承認ゲートなのか

承認を厚くすると、人が全部書き直す第二の作業になります。それではAI社員を入れる意味が薄れます。逆に、確認ゼロだと取り返しのつかない対外影響だけが残ります。

短いゲートの狙いは次の3点です。

1. **事実と約束の誤り**を止める（金額・日付・相手名・URL）
2. **トーンと権限**を止める（確定表現、値引き、納期確約）
3. **対象外領域**を止める（税務・労務・契約の個別判断）

「文章の上手さ」をゲートの主目的にしないのがコツです。上手さは後から直せる一方、誤った約束は後からでは取り消せません。

