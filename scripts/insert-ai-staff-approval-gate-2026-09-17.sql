## ゲートを崩さないための運用ルール

1. **公開・送信ボタンは人が持つ**  
   AIに本番公開や顧客送信の最終権限を渡さない。下書き保存までをAI、外への一手を人に固定します。

2. **「急ぎ」でも順序は変えない**  
   急ぎのときほど確認が飛びます。急ぎ用は「ゲート項目を減らす」ではなく、「ゲート項目を先に満たす下書き」を作らせます。

3. **成功例をテンプレにする**  
   一度通った成果物の型（見出し構成・注記の位置・禁止表現）を次の依頼にコピーします。毎回ゼロから依頼しない方が、ゲート通過率が上がります。

4. **失敗は範囲表に戻す**  
   同じ種類のミスが続くなら、その業務は「人が承認」から「最初から人」へ戻すか、入力データ（価格表・FAQ）を整えます。ゲートだけの対処にしない。

