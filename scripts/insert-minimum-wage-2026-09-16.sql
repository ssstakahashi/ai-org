## 2. なぜ労働条件の話として効くか

最低賃金は「賃金額」だけの話に見えがちですが、中小の現場では次の労働条件まわりと同時に動きます。

1. **就業規則・賃金規程の記載**（時給・日給・月給の換算、通勤手当や固定残業の扱い）
2. **求人・採用時の明示**（募集賃金が新最賃を下回っていないか）
3. **パート・アルバイトのシフトと総額人件費**（時間を増やす／単価を上げるの選択）
4. **事業場内最低賃金**（地域別最賃より高い社内ルールを置いている場合の追随）

特に月給制では、「月給÷所定労働時間」の時間換算で最賃割れがないかの確認が必要になります。固定残業代を含む場合も、基礎となる単価の見方が論点になりやすいです。ここは一般論で止め、自社の計算は社労士・給与担当で突合してください。

## 3. 発効前に中小が揃えるチェックリスト

10月〜12月の発効に間に合わせるなら、次の順が現実的です。

### A. 適用される地域別最低賃金と発効日を確定する

- 本社・店舗・工場ごとの都道府県を一覧にする
- 厚労省の答申表・各労働局の決定・官報公示で**確定額と発効日**を確認する（答申段階と決定後で差が出る場合がある）
- 東京のように10月1日発効が明示されている地域は、9月末までに給与計算マスタを更新できるか逆算する

### B. 時給・日給・月給の対象者を洗い出す

- 最低賃金近傍のパート・アルバイト
- 新卒・未経験採用の初任時給
- 嘱託・再雇用で時給換算が低い層
- 「手当を足せば足りる」運用になっていないか（どの手当が最賃の算定に入るかは個別確認）

### C. 求人票・社内掲示・給与ソフトを同時に直す

- 求人サイト・ハローワーク・自社採用ページの掲載額
- 給与計算ソフトの時給マスタ・割増の基礎
- 店舗の掲示・シフト表の単価欄

「給与ソフトだけ直して求人が古い」状態は、採用時点の明示義務やトラブルの温床になりやすいです。

### D. 人件費と価格・オペレーションをセットで見る

単価アップは、同じ時間でも総額人件費を押し上げます。飲食・小売・介護・運送など、最賃近傍の人員比率が高い業種ほど、次をセットで検討しやすいです。

- 稼働時間・シフトの組み直し（残業前提の穴埋めを減らす）
- 業務の標準化・記録のデジタル化（ムダな手作業を減らす）
- 公的な賃上げ支援・業務改善助成金などの情報収集（申請可否は最新案内で確認）

東京労働局は、令和8年9月1日〜10月31日を最低賃金・各種助成金の周知強化期間とし、業務改善助成金などのリーフレットも案内しています。

