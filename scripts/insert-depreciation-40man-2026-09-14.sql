## 少額減価償却資産の特例——何が変わるか

中小企業者等の少額減価償却資産の取得価額の損金算入の特例について、国税庁の令和8年度改正概要では次のとおり整理されています。

- **施行の目安**：令和8年4月1日以後に取得等（取得・製作・建設）をする減価償却資産
- **取得価額基準**：30万円未満 → **40万円未満**
- **適用期限**：3年延長
- **年の上限**：対象となる取得価額の合計は引き続き **年300万円**
- **対象法人**：同日以後の取得等について、常時使用する従業員数が **400人を超える法人は対象外**（改正前は500人超が対象外）

出典：国税庁「令和８年度 法人税関係法令の改正の概要」（少額減価償却資産の特例）  
https://www.nta.go.jp/publication/pamph/hojin/kaisei_gaiyo2026/pdf/A.pdf

財務省の令和8年度税制改正の大綱でも、取得価額を40万円未満に引き上げる旨が明記されています（所得税も同様）。

出典：財務省「令和８年度税制改正の大綱」  
https://www.mof.go.jp/tax_policy/tax_reform/outline/fy2026/08taikou_03.htm

### 現場で起きやすい誤解

| 誤解 | 実務上の注意 |
| --- | --- |
| 「全部40万円まで一括で落とせる」 | 1件あたりの基準は40万円未満。合計は年300万円が上限 |
| 「従業員400人ちょうどは対象外」 | 文言は「400人を超える」法人が除外。境界は専門家確認 |
| 「会計ソフトのマスタを変えなくても同じ」 | 取得日・判定基準が変わるので、購入稟議と資産登録の閾値を揃える |

PC・周辺機器・業務ソフト・備品など、「30万円前後で迷っていた買い物」が、4月以降は判定ラインが動きます。稟議書の金額帯や、固定資産台帳への登録ルールを、会計担当と先に一文で合わせておくと月末の手戻りが減ります。

なお、中小企業経営強化税制では、工具・器具備品の取得価額要件が30万円以上から **40万円以上** に引き上げられる見直しも同改正で触れられています。少額特例と「ちょうど逆方向」に閾値が動くため、どちらを使う想定か、購入前に分けておくと安全です。

## 防衛特別法人税——中小でも「申告の話」になる理由

防衛特別法人税は、令和7年改正により創設された付加税です。国税庁の案内では、次の骨格が示されています。

- **課税事業年度**：法人の令和8年4月1日以後に開始する各事業年度
- **納税義務者**：各事業年度の所得に対する法人税を課される法人
- **計算のイメージ**：一定の税額控除を適用しないで計算した法人税の額（基準法人税額）から **年500万円** を控除した金額に **4％**
- **重要**：防衛特別法人税額が **0であっても申告は必要**

出典：国税庁「防衛特別法人税が創設されました」（令和7年5月／令和8年6月改訂）  
https://www.nta.go.jp/publication/pamph/pdf/0025004-109_1.pdf

e-Tax側の案内でも、令和8年4月1日以後開始事業年度から納税義務者となり確定申告書の提出が必要であること、税額0でも申告が必要なこと、中間申告は令和9年4月1日以後開始事業年度から、と整理されています。

出典：e-Tax「防衛特別法人税の創設に関するご案内・留意事項について」  
https://www.e-tax.nta.go.jp/topics/2026/topics_20260417.htm

### 「うちは小さいから関係ない」が危ない理由

基礎控除（年500万円）により、基準法人税額が小さい法人では税額が出ないケースも多いです。それでも申告義務は残る、というのが現場の落とし穴です。

- 顧問税理士への「今年から別表がどう変わるか」の確認を、決算直前に残さない
- e-Tax・会計ソフトのバージョンと、防衛特別法人税の入力欄の有無を事前確認する
- 通算法人や事業年度が1年未満の場合は、基礎控除の按分がある（パンフレットに注記）

税額そのものより、「申告漏れ・様式の取り違え」の方が先に痛い、という順序で準備するのが現実的です。

